/**
 * Where the score's sounds go, in samples, from the cue sheet the stage hands the score
 * (ctx.cues) and the bar grid of src/cues.ts. A beat is 24 000 samples (120 bpm at 48 kHz), a
 * frame 2 000, so every frame-aligned position is exact.
 */
import type { ScoreContext } from '@aiv/pipeline/audio';
import { BEAT, BEATS_PER_BAR, BPM, at } from '../src/cues.ts';
import { SR } from './dsp.ts';

export interface Timeline {
  ctx: ScoreContext;
  /** samples in the film */
  n: number;
  /** the sample of bar `bar` (1-based) beat `b` (1-based, any fraction): exact, not frame-rounded */
  beat(bar: number, b?: number): number;
  /** the first sample of a film frame */
  frame(f: number): number;
  /** the sample of a cue by id (throws on an unknown id) */
  cue(id: string): number;
  /** a span cue's [start, end) in samples */
  span(id: string): [number, number];
  /** seconds → samples */
  s(t: number): number;
  /** the digital silences: [start, end) in samples, in time order */
  silences: [number, number][];
  /** the hard stop: the music cuts on bar 17's downbeat (the knock) */
  hardStop: number;
  /** cut points per bus: a clip never sounds past the next cut after its onset */
  cuts: { music: number[]; sfx: number[]; hall: number[]; room: number[] };
}

/** Samples per beat: exactly 24 000. */
export const BEAT_SAMPLES = (60 / BPM) * SR;

export function timeline(ctx: ScoreContext): Timeline {
  const ev = ctx.cues.events;
  const find = (id: string) => {
    const e = ev.find((x) => x.id === id);
    if (!e) throw new Error(`the score needs cue '${id}', which src/cues.ts does not have`);
    return e;
  };
  const frame = (f: number) => ctx.frameToSample(f);
  const silences = ev
    .filter((e) => e.kind === 'silence' && e.end !== undefined)
    .map((e) => [frame(e.frame), frame(e.end!)] as [number, number])
    .sort((a, b) => a[0] - b[0]);
  const hardStop = frame(find('knock-1').frame);
  const starts = silences.map((s) => s[0]);
  const uniq = (xs: number[]) => [...new Set(xs)].sort((a, b) => a - b);
  return {
    ctx,
    n: ctx.filmSamples,
    beat: (bar, b = 1) => Math.round(((bar - 1) * BEATS_PER_BAR + (b - 1)) * BEAT_SAMPLES),
    frame,
    cue: (id) => frame(find(id).frame),
    span: (id) => {
      const e = find(id);
      return [frame(e.frame), frame(e.end ?? e.frame)];
    },
    s: (t) => Math.round(t * SR),
    silences,
    hardStop,
    cuts: {
      music: uniq([hardStop, ...starts]),
      sfx: uniq(starts),
      hall: uniq([hardStop, ...starts]),
      room: uniq(starts),
    },
  };
}

/**
 * Clawd's footfalls, from the walks blocked in src/film/blocking.ts WALK_FRAMES (repeated here: a
 * score may not import picture code; src/film/blocking.test.ts checks they match): a walk from frame a to b lands a foot every beat after a, and once
 * more on arrival. Change them together.
 */
export const WALKS: readonly (readonly [number, number])[] = [
  [at(8, 2), at(9) + 8],
  [at(9) + 18, at(11, 1)],
  [at(11, 3) + 6, at(13) + 16],
  [at(14) + 8, at(16, 3)],
  [at(33, 2), at(34, 3)],
];

/**
 * Where each walk sits in the picture, so its footfalls sit there in the sound: per walk, keys
 * [u, pan, distance gain in dB] along the walk (u 0..1), linear between keys. Measured through
 * the V2 camera (src/film/journey.ts and blocking.ts): the pan is 0.8 x Clawd's screen x (-1 at
 * the left edge, 1 at the right), the gain -20 log10(distance / 2) below 0 dB for distances
 * past 2 units (nearer is never louder); one key per footfall (generated by measuring, not by
 * hand). The camera trucks with him, so he stays a little left of centre; walk 2 recedes up the
 * slope, the lane walk comes toward the door's camera, and the exit fades as the camera cranes
 * out of the book. src/film/sound.test.ts checks these against
 * the camera: change them together.
 */
export const STEP_PLACES: readonly (readonly (readonly [number, number, number])[])[] = [
  [[0, -0.25, 0], [0.38, -0.25, 0], [0.75, -0.21, 0], [1, -0.22, 0]],
  [[0, -0.27, 0], [0.22, -0.27, 0], [0.44, -0.38, 0], [0.67, -0.24, 0], [0.89, -0.08, 0], [1, -0.06, 0]],
  [[0, -0.24, 0], [0.21, -0.24, 0], [0.41, -0.1, 0], [0.62, -0.05, -0.5], [0.83, -0.08, -2.8], [1, -0.15, -4.6]],
  [[0, -0.27, -5.3], [0.14, -0.27, -5.3], [0.27, -0.25, -3.1], [0.41, -0.13, -1.6], [0.55, -0.09, -1.6], [0.68, -0.07, -1.3], [0.82, -0.16, -0.2], [0.95, 0.03, 0], [1, 0.03, 0]],
  [[0, 0, -4.9], [0.25, 0, -4.9], [0.5, 0, -12.7], [0.75, 0.11, -18.7], [1, 0.22, -20.5]],
];

/** A footfall's place: its pan and its distance gain (dB), from STEP_PLACES. */
export function stepPlace(walk: number, u: number): { pan: number; gainDb: number } {
  const keys = STEP_PLACES[walk];
  let k = 0;
  while (k < keys.length - 2 && u > keys[k + 1][0]) k++;
  const [u0, p0, g0] = keys[k];
  const [u1, p1, g1] = keys[k + 1];
  const t = Math.min(1, Math.max(0, (u - u0) / (u1 - u0)));
  return { pan: p0 + (p1 - p0) * t, gainDb: g0 + (g1 - g0) * t };
}

/** Every footfall: its frame, which walk it belongs to, and how far along that walk (0..1). */
export function footfalls(): { frame: number; walk: number; u: number }[] {
  const out: { frame: number; walk: number; u: number }[] = [];
  WALKS.forEach(([a, b], walk) => {
    for (let f = a + BEAT; f < b; f += BEAT) out.push({ frame: f, walk, u: (f - a) / (b - a) });
    out.push({ frame: b, walk, u: 1 });
  });
  return out;
}
